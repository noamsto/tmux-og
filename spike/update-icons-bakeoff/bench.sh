#!/usr/bin/env bash
# Head-to-head timing of the update-icons variants on the steady-state path.
# Run inside `nix develop` (needs hyperfine, strace, jq, go) after ./build.sh,
# or wrap it: nix shell nixpkgs#hyperfine nixpkgs#strace nixpkgs#jq -c ./bench.sh
#
#   bench.sh [RUNS] [VARIANTS...]     default: 250 runs of A B C D E
#
# Prints the load average before and after (rerun when the 1-minute load is
# above ~4 on this 16-core host), then mean/median/p95/min and forks per run.
set -euo pipefail

# shellcheck source=/dev/null  # sibling helper
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
resolve_build
resolve_bash

runs="${1:-250}"
shift || true
variants=("$@")
((${#variants[@]} > 0)) || variants=(A B C D E)

work="$(mktemp -d /tmp/og-bakeoff-bench.XXXX)"
root="$work/fx"
trap '"$SPIKE_DIR/fixture.sh" down "$root" || true; rm -rf "$work"' EXIT

"$SPIKE_DIR/fixture.sh" up "$root"
# shellcheck source=/dev/null  # generated by fixture.sh up
source "$root/env"
args="${OG_ARGS[0]} '' ${OG_ARGS[2]} '' ${OG_ARGS[4]} ${OG_ARGS[5]}"

cmds=()
for v in "${variants[@]}"; do
	variant_cmd "$v"
	cmds+=("${VCMD[*]} $args")
done

# One priming pass stamps every option, so the timed runs are the steady state
# (nothing left to write) and hyperfine's warmup only warms caches.
for v in "${variants[@]}"; do
	variant_cmd "$v"
	"${VCMD[@]}" "${OG_ARGS[@]}"
done

echo "== bench: $runs runs, variants: ${variants[*]}"
load_report
hyperfine -N --warmup 10 --runs "$runs" --export-json "$work/hf.json" --style basic \
	--command-name "" "${cmds[@]}" >/dev/null 2>&1 || {
	echo "hyperfine failed" >&2
	exit 1
}
load_report

echo
printf '%-3s %8s %8s %8s %8s %6s  %s\n' var mean_ms median_ms p95_ms min_ms forks 'exec breakdown'
i=0
for v in "${variants[@]}"; do
	stats="$(jq -r --argjson i "$i" '.results[$i].times | sort | length as $n |
		[(add/$n*1000), (.[($n/2|floor)]*1000), (.[(($n*0.95)|floor)]*1000), (.[0]*1000)] |
		map(.*100|round/100) | @tsv' "$work/hf.json")"
	variant_cmd "$v"
	strace -f -e trace=execve -o "$work/trace.$v" "${VCMD[@]}" "${OG_ARGS[@]}" >/dev/null 2>&1
	forks="$(grep -c 'execve(.*) = 0' "$work/trace.$v" || true)"
	breakdown="$(grep 'execve(.*) = 0' "$work/trace.$v" | sed 's/^[0-9]* execve("\([^"]*\)".*/\1/; s|.*/||' | sort | uniq -c | awk '{printf "%s×%s ", $2, $1}')"
	# shellcheck disable=SC2086  # stats is four tab-separated numbers
	printf '%-3s %8s %8s %8s %8s %6s  %s\n' "$v" $stats "$forks" "$breakdown"
	i=$((i + 1))
done
cp "$work/hf.json" "${OG_BENCH_JSON:-/tmp/og-bakeoff-last.json}"
